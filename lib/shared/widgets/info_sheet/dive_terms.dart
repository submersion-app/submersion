/// The term's name and short definition, with any depth figure in the
/// diver's units.
InfoEntry diveTermEntry(
  AppLocalizations l10n,
  UnitFormatter units,
  DiveTerm term,
) {
  return InfoEntry(term: _label(l10n, term), body: _body(l10n, units, term));
}

/// [diveTermEntry] for each of [terms], in the given order, without repeats.
List<InfoEntry> diveTermEntries(
  AppLocalizations l10n,
  UnitFormatter units,
  Iterable<DiveTerm> terms,
) {
  final seen = <DiveTerm>{};
  return [
    for (final term in terms)
      if (seen.add(term)) diveTermEntry(l10n, units, term),
  ];
}

/// A sheet of [title], [summary] and the [terms] a card shows, for the many
/// cards whose sheet needs no logic of its own.
InfoContent termsInfo(
  AppLocalizations l10n,
  UnitFormatter units, {
  required String title,
  String? summary,
  List<DiveTerm> terms = const [],
  String? background,
  String? howToUse,
}) {
  return InfoContent(
    title: title,
    summary: summary,
    terms: diveTermEntries(l10n, units, terms),
    background: background,
    howToUse: howToUse,
  );
}

