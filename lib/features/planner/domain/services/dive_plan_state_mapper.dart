    maxO2DepthMeters: state.maxO2DepthMeters,
    clearMaxO2DepthMeters: state.maxO2DepthMeters == null,
    maxO2DepthExplicitlyOff: state.maxO2DepthExplicitlyOff,
    hypercapniaAmv: state.hypercapniaAmv,
