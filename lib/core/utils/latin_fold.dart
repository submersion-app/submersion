/// [text] lower-cased, with Latin diacritics, apostrophes and the ʻokina
/// dropped, so a
/// search typed without accents still matches.
String foldLatinForSearch(String text) {
  final buffer = StringBuffer();
  for (final rune in text.toLowerCase().runes) {
    final char = String.fromCharCode(rune);
    if (char == 'ʻ' || char == '\'') continue;
    buffer.write(_latinFolds[char] ?? char);
  }
  return buffer.toString();
}
