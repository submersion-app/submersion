final Map<String, String> _namesByCode = {
  for (final currency in kIsoCurrencies) currency.code: currency.name,
};

/// The English name of [code] (e.g. 'BRL' -> 'Brazilian real'), or null for
/// a code outside the catalog.
String? isoCurrencyName(String code) => _namesByCode[code.trim().toUpperCase()];
