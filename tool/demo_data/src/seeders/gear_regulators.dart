List<DemoGear> _stageRegulator(String n, StoryMilestone bought) {
  final label = n == 'bailout' ? 'Bailout' : 'Stage $n';
  return [
    DemoGear(
      'reg-stage-$n',
      '$label regulator',
      EquipmentType.regulator,
      brand: 'Apeks',
      model: 'XTX40 stage set',
      bought: bought,
      serviceIntervalDays: 365,
      uses: n == 'bailout' ? const {KitUse.ccr} : const {KitUse.tech},
    ),
    DemoGear(
      'fs-stage-$n',
      '$label first stage',
      EquipmentType.firstStage,
      brand: 'Apeks',
      model: 'DS4',
      bought: bought,
    ),
    DemoGear(
      'ss-stage-$n',
      '$label second stage',
      EquipmentType.secondStage,
      brand: 'Apeks',
      model: 'XTX40',
      bought: bought,
    ),
    _hose('hose-stage-$n', '$label hose', 'lp', 1.0, bought: bought),
    _hose('hose-stage-$n-hp', '$label gauge hose', 'hp', 0.15, bought: bought),
    DemoGear(
      'spg-stage-$n',
      '$label button gauge',
      EquipmentType.instrument,
      brand: 'Apeks',
      model: 'Button SPG',
      bought: bought,
    ),
  ];
}
