#!/usr/bin/env python3
"""Compile the trim figure's side-view artwork into Dart (issue #5028).

Sources: tool/figure_side/manifest.json and one SVG per piece at
tool/figure_side/<id>.svg, drawn in the 400 by 200 side space (y down, the
diver prone and facing left, back up, straight pose).
Output:  lib/features/trim_calculator/presentation/widgets/trim_artwork.gen.dart

    python3 tool/build_trim_artwork.py            # write the Dart file
    python3 tool/build_trim_artwork.py --verify   # check the sources and that the Dart file is current

The SVG subset, its rejections and the bounds check are the gear figure's
(tool/build_figure_artwork.py); each piece names the body segment it moves
with in place of a view.
"""
import argparse
import hashlib
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_figure_artwork as fig  # noqa: E402

ROOT = fig.ROOT
SRC = ROOT / "tool" / "figure_side"
OUT = ROOT / "lib" / "features" / "trim_calculator" / "presentation" / "widgets" / "trim_artwork.gen.dart"
WIDTH, HEIGHT = 400.0, 200.0
SEGMENTS = ["torso", "arm", "shin", "foot"]


def load_manifest():
    data = json.loads((SRC / "manifest.json").read_text(encoding="utf-8"))
    pieces = data.get("pieces")
    if not isinstance(pieces, list) or not pieces:
        raise fig.FigureError("manifest.json needs a non-empty pieces list")
    seen = set()
    for piece in pieces:
        pid = piece.get("id")
        if not isinstance(pid, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", pid):
            raise fig.FigureError("bad piece id: {!r}".format(pid))
        if pid in seen:
            raise fig.FigureError("duplicate piece id: {}".format(pid))
        seen.add(pid)
        if piece.get("segment") not in SEGMENTS:
            raise fig.FigureError("{}: segment must be one of {}".format(pid, SEGMENTS))
        if not isinstance(piece.get("layer"), int) or piece["layer"] < 0:
            raise fig.FigureError("{}: layer must be a non-negative integer".format(pid))
        roles = piece.get("roles")
        if not isinstance(roles, list) or not roles or any(r not in fig.ROLES for r in roles):
            raise fig.FigureError("{}: roles must be a non-empty list drawn from {}".format(pid, fig.ROLES))
    orphans = [s for s in sorted(f.stem for f in SRC.glob("*.svg")) if s not in seen]
    if orphans:
        raise fig.FigureError("SVG files without a manifest entry: {}".format(", ".join(orphans)))
    return pieces


def compile_pieces(pieces):
    compiled = []
    for piece in pieces:
        svg_file = SRC / "{}.svg".format(piece["id"])
        if not svg_file.exists():
            raise fig.FigureError("{}: {} is missing".format(piece["id"], svg_file.name))
        shapes = fig.shapes_of(svg_file)
        if len(shapes) != len(piece["roles"]):
            raise fig.FigureError("{}: {} shapes but {} roles".format(piece["id"], len(shapes), len(piece["roles"])))
        for d in shapes:
            for x, y in fig.path_points(d):
                if not (0 <= x <= WIDTH and 0 <= y <= HEIGHT):
                    raise fig.FigureError("{}: a shape leaves the side box at ({}, {})".format(piece["id"], fig.n(x), fig.n(y)))
        compiled.append({"id": piece["id"], "segment": piece["segment"], "layer": piece["layer"],
                         "paths": list(zip(piece["roles"], shapes))})
    return compiled


def digest():
    h = hashlib.sha256()
    files = sorted(list(SRC.glob("*.svg")) + [SRC / "manifest.json"], key=lambda f: f.name)
    for f in files:
        h.update("{}\n".format(f.name).encode("utf-8"))
        h.update(f.read_bytes().replace(b"\r\n", b"\n").replace(b"\r", b"\n"))
    return h.hexdigest()


def emit_dart(compiled, sources_digest):
    lines = [
        "// GENERATED by tool/build_trim_artwork.py from tool/figure_side/. Do not edit.",
        "// sources-digest: {}".format(sources_digest),
        "// dart format off",
        "",
        "import 'package:submersion/core/buoyancy/trim/trim_body.dart';",
        "import 'package:submersion/features/trim_calculator/presentation/widgets/trim_piece_data.dart';",
        "import 'package:submersion/features/equipment/figure/domain/figure_piece_data.dart';",
        "import 'package:submersion/features/equipment/figure/domain/figure_role.dart';",
        "",
        "/// SHA-256 over the manifest and every SVG, so a test can tell when this",
        "/// file is stale against its sources.",
        "const String trimArtworkDigest = '{}';".format(sources_digest),
        "",
        "/// Every side-view piece by id.",
        "const Map<String, TrimPieceData> trimArtwork = {",
    ]
    for piece in compiled:
        lines.append("  '{}': TrimPieceData(".format(piece["id"]))
        lines.append("    id: '{}',".format(piece["id"]))
        lines.append("    segment: TrimSegment.{},".format(piece["segment"]))
        lines.append("    layer: {},".format(piece["layer"]))
        lines.append("    paths: [")
        for role, d in piece["paths"]:
            lines.append("      FigurePathData(role: FigureRole.{}, d: '{}'),".format(role, d))
        lines.append("    ],")
        lines.append("  ),")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify", action="store_true", help="check sources and that the Dart file is current")
    args = parser.parse_args(argv)
    try:
        compiled = compile_pieces(load_manifest())
        text = emit_dart(compiled, digest())
    except (fig.FigureError, ET.ParseError, KeyError, ValueError) as error:
        print("FAIL {}".format(error))
        return 1
    if args.verify:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("FAIL {} is stale; run python3 tool/build_trim_artwork.py".format(OUT.relative_to(ROOT)))
            return 1
        print("OK {} pieces current".format(len(compiled)))
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("wrote {} ({} pieces)".format(OUT.relative_to(ROOT), len(compiled)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
